// ============================================================
// Копирование между панелями (в т.ч. между разными БД)
// ============================================================
// Вся тяжёлая логика вынесена в FAR.transferBetweenSides('copy')
// в модуле 35-multi-db.js. Здесь — только точка входа для
// кнопки тулбара и хоткея Ctrl+Insert.
//
// Работает в двух режимах:
//   • одна БД на обе панели  — обычное копирование документов;
//   • разные БД на панелях   — чтение из БД-источника и запись
//                              в БД-приёмник через blob-перенос.
// ============================================================

FAR.copySelected = function () {
    return FAR.transferBetweenSides('copy');
};